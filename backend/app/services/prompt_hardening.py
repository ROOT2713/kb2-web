"""Prompt 硬化补丁 —— 费用类表格的「硬模板 + 列数自检」

问题定位（实测依据，非推测）
--------------------------
截图那道的真实回答里，表格是这样输出的：

    | 地市/标准 | 费用类型 | 金额（万元） | 计算公式 | 依据文件及表号 |
    |---|----|----|                      ← 只有 3 列，表头是 5 列
    | 省级 | 验收测评费率表未检索到 | — | — | 《电子政务工程造价指导书（2019年）》 |

关键观察：**分隔行列数写错的只有分隔行，数据行 5 列全对**。
这与「LLM 不理解表格」无关——是**列数计数器在抄写分隔线时丢拍**（`|---|---|---|`
比表头少敲两格）。当前 prompt 只说「固定五列表格 / 分隔线 |---|---|---|---|---|」，
是**描述性约束**：LLM 需要自己把 5 个 `---` 数一遍，长 prompt 下注意力衰减就会漏。

解决思路：把「描述」升级为「模板 + 自检」
--------------------------------------
1. **硬模板**：把整张空表（含正确分隔行）以 `代码块` 形式给出，LLM 只需"填空"，
   不需要自己生成分隔线 —— 把它从「生成任务」降级为「复制任务」；
2. **列数自检**：插入一条**可执行的自查指令**（输出前数一遍每行管道符），
   把校验责任显式交还给模型，而不是假设它记得；
3. **降级条款**：给一条"如果不确定就改用列表"的出口，避免它硬撑出一张歪表
   （歪表比列表更难读，且更伤可信度）。

设计约束
--------
- 纯字符串常量与纯函数，零依赖、零副作用，可被任何 prompt 拼装点引用；
- 不改变既有 prompt 结构，只**追加**一段，接入成本 = 一行 `+`；
- 与 `answer_structurer.py` 的 `repair_flags` 形成闭环：
  prompt 硬化负责「少产生坏表」，结构器负责「坏了也能显示」。

代码基线：main `b0a9dff`（`backend/app/api/query_engine.py`）
"""

from __future__ import annotations

from typing import List

# ── 费用类查询的固定五列表头（唯一真源，prompt 与自检共用）──
FEE_TABLE_HEADERS: List[str] = [
    "地市/标准",
    "费用类型",
    "金额（万元）",
    "计算公式",
    "依据文件及表号",
]

# ── 硬模板：整张空表，含已对齐的分隔行 ──
FEE_TABLE_TEMPLATE = """| 地市/标准 | 费用类型 | 金额（万元） | 计算公式 | 依据文件及表号 |
|---|---|---|---|---|
|  |  |  |  |  |
|  |  |  |  |  |"""

# ── 输出前自检：把列数校验显式化为可执行动作 ──
FEE_TABLE_SELF_CHECK = (
    "   **【输出前自检 — 必做，逐条核对】**\n"
    "      1. 数一数表头行：管道符必须是 6 个（5 列）；\n"
    "      2. 数一数分隔行：必须是 `|---|---|---|---|---|`，"
    "同样 6 个管道符、5 组 `---`，**不得少敲或多敲**；\n"
    "      3. 数一数每一个数据行：也必须是 5 个单元格，"
    "不足 5 个用 `—` 补齐，超出 5 个把多余内容合并进「依据文件及表号」列；\n"
    "      4. 确认表格**上下各留一个空行**，紧邻表格的行不得是普通文字（否则渲染器不识别）；\n"
    "      5. 任何一行对不上，**宁可改成无序列表**（`- 地市：金额（公式，依据）`），"
    "也不要输出一张列数不齐的表格。\n"
    "      —— 列数不齐的表格会被前端解析器判为「已修复」，并在质量看板上计入 "
    "`separator_column_mismatch`，请避免。\n"
)

# ── 可直接追加到 _fee_rules 末尾的完整片段 ──
FEE_TABLE_HARDENING = (
    "   l. **【硬模板 — 费用类表格一律照抄此表，不要自己敲分隔线】**：\n"
    "      直接复制下面这张空表，只在数据格里填内容：\n"
    "      ```\n"
    f"      {FEE_TABLE_TEMPLATE}\n"
    "      ```\n"
    "      - **表头与分隔行必须逐字符照抄**，禁止改列名、禁止增删列、"
    "禁止把多行内容折进一个单元格；\n"
    "      - 每个地市/标准占一行；同一地市多档位则占多行；\n"
    "      - 「金额（万元）」只填数字，**不带单位**（单位已在表头）；\n"
    "      - 确实检索不到的，金额列填 `—`，并在「依据文件及表号」列写明"
    "「该地市费率表未检索到」，**不得整行省略**；\n"
    "\n" + FEE_TABLE_SELF_CHECK
)

# ── 建议替换【输出要求】#2 的正文（把结构化格式的表格化写法前置）──
OUTPUT_REQ_2_PATCH = (
    "2. **数值类问题的输出格式**：当用户询问具体数值（费用、技术参数、标准号等）时，"
    "按以下结构化格式输出：\n"
    "   ```\n"
    "   【问题类别】\n"
    "   - 参数名称：数值（来源：文档名称，表号/条款号）\n"
    "   ```\n"
    "   **若同一类数值涉及多个对象（多地市/多标准/多档位）且 ≥3 项，"
    "必须改用表格**，不得写成多行列表：\n"
    "   ```\n"
    f"   {FEE_TABLE_TEMPLATE}\n"
    "   ```\n"
    "   表头与分隔行**逐字符照抄**，数据行严格 5 列。每个数值必须标注来源。\n"
)


def build_fee_hint() -> str:
    """返回追加到 `_fee_rules` 变量末尾的硬化片段（一行 `+` 即可接入）。"""
    return FEE_TABLE_HARDENING


def table_self_check_detail() -> str:
    """供测试与联调单独取用自检条款。"""
    return FEE_TABLE_SELF_CHECK


